test('commission: the sign-off, and sending a sheet back to Finance', async () => {
  const d = cmDb({ runs: [aRun({ id: uid('s1') })] });
  await assert.rejects(() => _FNS.commDecide(d, ADMIN_G, { id: uid('s1'), approve: false }),
    e => e.status === 400 && /sababu|reason/i.test(e.message), 'sending it back needs a reason');
  const r = await _FNS.commDecide(d, ADMIN_G, { id: uid('s1'), approve: true });
  assert.equal(r.status, 'approved');
  const [row] = d._dump('commission_runs');
  assert.equal(row.approved_by, 'NEEMA M'); assert.ok(row.approved_at);
  // Sent back: the sign-off is cleared so Finance can rebuild.
  const r2 = await _FNS.commDecide(d, ADMIN_G, { id: uid('s1'), approve: false, comment: 'Kiwango cha A06 si sahihi' });
  assert.equal(r2.status, 'draft');
  assert.equal(row.approved_by, null); assert.equal(row.approved_at, null);
  assert.equal(row.comment, 'Kiwango cha A06 si sahihi');
  // An empty sheet is not something to sign.
  const empty = cmDb({ runs: [aRun({ id: uid('s2'), qty: 0, amount: 0 })] });
  await assert.rejects(() => _FNS.commDecide(empty, ADMIN_G, { id: uid('s2'), approve: true }),
    e => e.status === 400 && /tupu|nothing on this sheet/i.test(e.message));
  await assert.rejects(() => _FNS.commDecide(d, ADMIN_G, { id: uid('zz'), approve: true }), e => e.status === 400);
});

test('commission: the audit checklist is a GATE, not a decoration', async () => {
  const mk = () => cmDb({ runs: [aRun({ id: uid('p1'), status: 'approved', approvedBy: 'NEEMA M', approvedAt: '2026-10-01T07:00:00Z' })] });
  // Not signed off yet: no payment at all.
  const draft = cmDb({ runs: [aRun({ id: uid('p1') })] });
  await assert.rejects(() => _FNS.commPay(draft, FIN, { id: uid('p1'), paymentRef: 'TX1', checks: ALL_CHECKS }),
    e => e.status === 400 && /idhini|sign-off/i.test(e.message));
  // No reference: SOP A.7 has nothing to file.
  const d = mk();
  await assert.rejects(() => _FNS.commPay(d, FIN, { id: uid('p1'), checks: ALL_CHECKS }),
    e => e.status === 400 && /kumbukumbu|reference/i.test(e.message));
  // Four of five ticked is not a completed checklist, and the message says which is missing.
  for (const miss of Object.keys(ALL_CHECKS)) {
    const partial = { ...ALL_CHECKS }; delete partial[miss];
    await assert.rejects(() => _FNS.commPay(mk(), FIN, { id: uid('p1'), paymentRef: 'TX1', checks: partial }),
      e => e.status === 400 && /ukaguzi|checklist/i.test(e.message), 'missing ' + miss);
  }
  assert.equal(d._dump('commission_runs')[0].status, 'approved', 'and nothing was paid');
  // All five, with a reference: paid AND cleared in the same write.
  const ok = mk();
  const r = await _FNS.commPay(ok, FIN, { id: uid('p1'), paymentRef: 'TX-9911', checks: ALL_CHECKS });
  assert.equal(r.status, 'paid'); assert.ok(r.clearedAt);
  const [row] = ok._dump('commission_runs');
  assert.equal(row.status, 'paid'); assert.equal(row.paid_by, 'JANETH');
  assert.equal(row.payment_ref, 'TX-9911'); assert.ok(row.cleared_at);
  for (const c of ['chk_unpaid_list', 'chk_watu_verified', 'chk_advance_topups', 'chk_voucher', 'chk_bank_statement']) {
    assert.equal(row[c], true, c + ' is recorded against the cycle, not just ticked on a screen');
  }
});

test('commission: SOP A.6 -- a cleared cycle can never be paid a second time', async () => {
  const d = cmDb({ runs: [aRun({ id: uid('c1'), status: 'approved', approvedBy: 'NEEMA M' })] });
  await _FNS.commPay(d, FIN, { id: uid('c1'), paymentRef: 'TX-1', checks: ALL_CHECKS });
  await assert.rejects(() => _FNS.commPay(d, FIN, { id: uid('c1'), paymentRef: 'TX-2', checks: ALL_CHECKS }),
    e => e.status === 400 && /A\.6/.test(e.message) && /mara ya pili|twice/i.test(e.message));
  assert.equal(d._dump('commission_runs')[0].payment_ref, 'TX-1', 'the first payment stands');
  // Nor can it be signed back down and re-run.
  await assert.rejects(() => _FNS.commDecide(d, ADMIN_G, { id: uid('c1'), approve: false, comment: 'oops' }),
    e => e.status === 400 && /imelipwa|already been paid/i.test(e.message));
  await assert.rejects(() => _FNS.commBuild(d, FIN, { period: MONTH }), e => e.status === 400);
  /* AND THE RACE: two people pressing Pay at the same instant. The guarded update matches
     nothing for the second, which is exactly what cleared_at is for. */
  const race = cmDb({ runs: [aRun({ id: uid('c2'), status: 'approved', approvedBy: 'NEEMA M' })] });
  const raw = race.from.bind(race);
  let armed = true;
  race.from = name => {
    const q = raw(name);
    if (name === 'commission_runs' && armed) {
      const u = q.update.bind(q);
      q.update = p => { armed = false; race._dump('commission_runs')[0].cleared_at = '2026-10-01T09:00:00Z';
        race._dump('commission_runs')[0].status = 'paid'; return u(p); };
    }
    return q;
  };
  await assert.rejects(() => _FNS.commPay(race, FIN, { id: uid('c2'), paymentRef: 'TX-3', checks: ALL_CHECKS }),
    e => e.status === 400 && /A\.6/.test(e.message));
});

