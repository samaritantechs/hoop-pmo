test('commission: rates are edited from the pane, and the sheet reads back whole', async () => {
  const d = cmDb({ agents: [reg('ASHA', 'Field_Officer', 'DAR')], loans: [loan('ASHA')] });
  await _FNS.commRateSave(d, FIN, { role: ' field officer ', item: ' a07 ', amount: '12000' });
  const [r] = d._dump('commission_rates');
  assert.equal(r.role, 'FIELD_OFFICER'); assert.equal(r.item, 'A07'); assert.equal(r.amount, 12000);
  assert.equal(r.updated_by, 'JANETH');
  // Saving the same pair corrects it rather than adding a second.
  await _FNS.commRateSave(d, FIN, { role: 'FIELD_OFFICER', item: 'A07', amount: 9000 });
  assert.equal(d._dump('commission_rates').length, 1);
  assert.equal(d._dump('commission_rates')[0].amount, 9000);
  // Blank means the wildcard, which is how a single company-wide rate is set.
  await _FNS.commRateSave(d, FIN, { amount: 3000 });
  assert.ok(d._dump('commission_rates').some(x => x.role === 'ANY' && x.item === 'ANY'));
  await assert.rejects(() => _FNS.commRateSave(d, FIN, { role: 'ANY', item: 'ANY' }), e => e.status === 400);
  await assert.rejects(() => _FNS.commRateSave(d, FIN, { role: 'ANY', item: 'ANY', amount: -5 }), e => e.status === 400);
  await _FNS.commRateDelete(d, FIN, { role: 'FIELD_OFFICER', item: 'A07' });
  assert.equal(d._dump('commission_rates').length, 1);
  await assert.rejects(() => _FNS.commRateDelete(d, FIN, { role: 'FIELD_OFFICER' }), e => e.status === 400);
  // And the sheet: the run, its lines, and the checklist labels the pane draws.
  await _FNS.commBuild(d, FIN, { period: MONTH });
  const id = String(d._dump('commission_runs')[0].id);
  const s = await _FNS.commSheet(d, ADMIN_G, { id });
  assert.equal(s.run.period, MONTH); assert.equal(s.run.status, 'draft');
  assert.equal(s.lines.length, 1); assert.equal(s.lines[0].agent, 'ASHA');
  assert.equal(s.checks.length, 5);
  assert.ok(s.checks.every(c => c.key && c.label));
  await assert.rejects(() => _FNS.commSheet(d, FIN, { id: 'nope' }), e => e.status === 400);
});

