test('commission: a draft may be rebuilt; a signed sheet may not', async () => {
  const d = cmDb({
    loans: [loan('ASHA', { n: 1 })], agents: [reg('ASHA', 'Field_Officer', 'DAR')],
    rates: [rate('ANY', 'ANY', 5000)],
  });
  await _FNS.commBuild(d, FIN, { period: MONTH });
  assert.equal(d._dump('commission_runs')[0].total_amount, 5000);
  // A second phone lands, and the draft is rebuilt to match.
  d._dump('watu_loans').push(loan('ASHA', { n: 2 }));
  await _FNS.commBuild(d, FIN, { period: MONTH });
  assert.equal(d._dump('commission_runs').length, 1, 'rebuilt, not duplicated');
  assert.equal(d._dump('commission_runs')[0].total_amount, 10000);
  assert.equal(d._dump('commission_lines').length, 1, 'and the old lines were replaced, not added to');
  assert.equal(d._dump('commission_lines')[0].qty, 2);
  // Signed off: the figure is frozen, whatever lands afterwards.
  const id = String(d._dump('commission_runs')[0].id);
  await _FNS.commDecide(d, ADMIN_G, { id, approve: true });
  d._dump('watu_loans').push(loan('ASHA', { n: 3 }));
  await assert.rejects(() => _FNS.commBuild(d, FIN, { period: MONTH }),
    e => e.status === 400 && /idhinishwa|signed off/i.test(e.message));
  assert.equal(d._dump('commission_runs')[0].total_amount, 10000, 'the signed figure did not move');
});

