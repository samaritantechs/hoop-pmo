test('commission: a phone is priced by the seller\'s role and its model, most specific first', async () => {
  const d = cmDb({
    loans: [loan('ASHA', { n: 1, model: 'A07' }), loan('ASHA', { n: 2, model: 'A06' }),
      loan('JUMA', { n: 3, model: 'A07' }), loan('MOSES', { n: 4, model: 'A07' })],
    agents: [reg('SIMON', 'Regional_Manager', 'DAR'), reg('ASHA', 'Field_Officer', 'DAR'),
      reg('JUMA', 'Team_Leader', 'DAR'), reg('MOSES', 'Field_Officer', 'DAR')],
    rates: [
      rate('FIELD_OFFICER', 'A07', 10000),   // the exact pair
      rate('FIELD_OFFICER', 'ANY', 7000),    // this role, any model
      rate('ANY', 'A07', 5000),              // any role, this model
    ],
  });
  const r = await _FNS.commBuild(d, FIN, { period: MONTH, kind: 'monthly' });
  assert.equal(r.from, '2026-09-01'); assert.equal(r.to, '2026-09-30');
  const lines = d._dump('commission_lines');
  const asha = lines.find(l => l.agent === 'ASHA');
  assert.equal(asha.qty, 2);
  assert.equal(asha.amount, 10000 + 7000, 'the exact pair for the A07, the role wildcard for the A06');
  const juma = lines.find(l => l.agent === 'JUMA');
  assert.equal(juma.amount, 5000, 'no TEAM_LEADER rate, so the model wildcard');
  assert.equal(r.totalQty, 4);
  assert.equal(r.totalAmount, 10000 + 7000 + 5000 + 10000);
  // SOP A.4: the five fields are on the sheet.
  assert.equal(asha.agent_phone, '074'); assert.equal(asha.rsm, 'SIMON'); assert.equal(asha.role, 'Field_Officer');
  const [run] = d._dump('commission_runs');
  assert.equal(run.status, 'draft'); assert.equal(run.created_by, 'JANETH');
  assert.equal(run.period, MONTH); assert.equal(run.kind, 'monthly');
});

