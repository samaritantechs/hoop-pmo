/* =========================================================================================
   COMMISSION -- the rate table, the run, the payment sheet, and the CLEARED stamp.

     Finance SOP A.1  the daily 9:00 AM and monthly schedules, generated by the system
     Finance SOP A.3  "Cross-check that each phone being paid for is correctly linked to the
                       agent who sold it, before approving payment"
     Finance SOP A.4  the payment sheet -- agent name, sales quantity, commission amount,
                       phone number, and the RSM the agent falls under -- forwarded to the
                       Administration approval group for sign-off
     Finance SOP A.6  "mark the payment as 'cleared' in the system IMMEDIATELY, to prevent
                       duplicate payment"
     Finance SOP A    the Commission Audit Checklist, filed against every payment cycle

   THE POINT IS A.6. The arithmetic could be done in a spreadsheet; what a spreadsheet cannot
   do is refuse to pay the same period twice.

   THE PERMISSION IS THE NAV. Nothing below names a Finance Manager or an Administrator.
   ========================================================================================= */
const FIN = { code: 'F1', name: 'JANETH', role: 'OFFICER', teams: null, tabs: ['commission'], readOnly: false };
const ADMIN_G = { code: 'D1', name: 'NEEMA M', role: 'OFFICER', teams: null, tabs: ['commappr'], readOnly: false };
const VIEWER = { code: 'V1', name: 'Auditor', role: 'AUDITOR', teams: null, tabs: ['commission', 'commappr'], readOnly: true };
