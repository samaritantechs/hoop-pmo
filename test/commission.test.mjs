test('commission: building and signing off are two grants, and nobody holds both by accident', async () => {
  const d = cmDb({ runs: [aRun({ id: uid('r1') })] });
  const denied = async (fn, user, args) => {
    await assert.rejects(() => _FNS[fn](d, user, args || {}), e => e.status === 403,
      fn + ' must refuse a user who was never granted its pane');
  };
  // Finance builds and pays; it does not sign its own sheet off.
  await denied('commDecide', FIN, { id: uid('r1'), approve: true });
  // The approval group signs; it does not build, price or pay.
  await denied('commBuild', ADMIN_G, { period: MONTH });
  await denied('commPay', ADMIN_G, { id: uid('r1') });
  await denied('commRateSave', ADMIN_G, { role: 'ANY', item: 'ANY', amount: 1 });
  // Somebody with neither sees nothing at all.
  await denied('commRuns', OTHER); await denied('commRates', OTHER);
  await denied('commSheet', OTHER, { id: uid('r1') });
  // Both panes read each other's work -- that is the point of a sign-off.
  assert.ok(Array.isArray((await _FNS.commRuns(d, FIN, {})).rows));
  assert.ok(Array.isArray((await _FNS.commRuns(d, ADMIN_G, {})).rows));
  // View-only reads everything and moves no money.
  assert.ok((await _FNS.commRates(d, VIEWER)).rates);
  for (const [fn, args] of [['commBuild', { period: MONTH }], ['commDecide', { id: uid('r1'), approve: true }],
    ['commPay', { id: uid('r1'), paymentRef: 'X', checks: ALL_CHECKS }],
    ['commRateSave', { role: 'ANY', item: 'ANY', amount: 1 }]]) {
    await assert.rejects(() => _FNS[fn](d, VIEWER, args), e => e.status >= 400 && e.status < 500, fn);
  }
  assert.equal(d._dump('commission_runs')[0].status, 'draft');
  assert.ok((await _FNS.commRuns(d, OWNER, {})).rows, 'ADMIN IS FULL ACCESS EVERYWHERE');
});

test('commission: the navs are tickable, the money writes are audited, and the checklist is one list', () => {
  const src = fs.readFileSync(new URL('../api/portal.js', import.meta.url), 'utf8');
  const m = /const NAV_TABS = \[([^\]]+)\]/.exec(src);
  for (const k of ['commission', 'commappr']) assert.ok(m[1].includes(`'${k}'`), k + ' is a nav the owner can tick');
  for (const fn of ['commBuild', 'commDecide', 'commPay', 'commRateSave', 'commRateDelete']) {
    assert.match(src, new RegExp("AUDITED\\.add\\('" + fn + "'\\)"), fn + ' is audited: this is money leaving');
  }
  const sql = fs.readFileSync(new URL('../db/migrations/RUN-ME-2026-09-09-commission.sql', import.meta.url), 'utf8');
  for (const t of ['commission_rates', 'commission_runs', 'commission_lines']) {
    assert.match(sql, new RegExp('create table if not exists ' + t + ' \\('), t + ' is created idempotently');
  }
  assert.match(sql, /unique \(period, kind\)/, 'a period cannot be run twice, enforced by the database');
  assert.match(sql, /unique \(run_id, agent\)/, 'nor an agent paid twice inside one sheet');
  assert.match(sql, /cleared_at/, 'and SOP A.6 has a column of its own');
  // The five checklist rows the SOP names, in one place the pane and the gate both read.
  const checks = /const COMM_CHECKS = \[([\s\S]*?)\];/.exec(src);
  assert.ok(checks);
  for (const k of ['chk_unpaid_list', 'chk_watu_verified', 'chk_advance_topups', 'chk_voucher', 'chk_bank_statement']) {
    assert.ok(checks[1].includes(k), k + ' is on the checklist');
    assert.ok(sql.includes(k), k + ' is a column');
  }
});

